#include <string>
#include <vector>

void divisor_count() {
    int n = 36;
    int count = 0;
    for (int d = 1; d <= n; ++d) {
        if (n % d == 0) count += 1;
    }
    (void)count;
}

void binomial_small() {
    int n = 6, k = 2;
    int result = 1;
    for (int i = 1; i <= k; ++i) result = result * (n - k + i) / i;
    (void)result;
}

void digit_sum() {
    int n = 9081;
    int total = 0;
    while (n > 0) {
        total += n % 10;
        n /= 10;
    }
    (void)total;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

extern "C" int vivid_haven();
extern "C" void calm_quartz();
extern "C" void subtle_willow();
extern "C" void subtle_vale();

int main() {
    divisor_count();
    binomial_small();
    digit_sum();
    text_contains();
    calm_quartz();
    subtle_willow();
    subtle_vale();
    return vivid_haven();
}
